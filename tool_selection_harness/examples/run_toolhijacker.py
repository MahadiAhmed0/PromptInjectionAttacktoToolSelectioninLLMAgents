"""End-to-end reproduction of ToolHijacker (NDSS 2026) inside the harness.

Pipeline (all confined to the local benchmark library):
  1. Baseline pass: report ACC and HR@k without any injection.
  2. Manual baselines: the paper's five manual prompt-injection attacks
     (naive, escape, context ignore, fake completion, combined); report
     ASR (target_selection_rate) and AHR (target_retrieval_rate) per attack.
  3. ToolHijacker gradient-free: R generated by an LLM from shadow task
     descriptions + S optimized via tree search (paper Algorithm 1).
  4. Optional ToolHijacker gradient-based (--gradient-based): GCG-style
     token optimization of S against a local gpt2, and HotFlip-style
     optimization of R against a local MiniLM. Requires model downloads.
  5. Detection (Table X): known-answer, PPL, and PPL-W detectors evaluated
     on the benign library vs. the crafted malicious documents (FNR/FPR/AUC
     with a dataset-adaptive 1% FPR calibration).

Usage:
    python examples/run_toolhijacker.py [--task weather] [--queries 10]
        [--k 5] [--offline] [--gradient-based] [--grad-iterations 20]

Set OPENAI_API_KEY or ANTHROPIC_API_KEY to use real LLMs for the attacker
and shadow roles; otherwise deterministic offline mocks are used.

Ethics note: this script reproduces published attacks strictly against the
synthetic benchmark library for defense evaluation. Do not point it at real
agents or production tool registries.
"""

